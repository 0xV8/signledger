"""SLCS/1 conformance vectors.

``tests/vectors/slcs1.json`` is the cross-language contract. A verifier written in
another language is correct exactly when it reproduces these bytes, so the expected
values in that file are hand-written, never captured from this implementation - a vector
generated by the code it is meant to police proves nothing.

The file is self-contained: every input is expressed in a small tagged JSON dialect that
is documented inside the file itself, and every expectation is given both as text and as
the hex of its UTF-8 bytes, so no reader has to guess at an escaping convention.
"""

import hashlib
import json
from datetime import datetime
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from signledger.core.entry import Entry
from signledger.core.exceptions import CanonicalizationError
from signledger.crypto.canonical import canonicalize, entry_preimage
from signledger.crypto.hashing import HashChain, genesis_hash

VECTORS_PATH = Path(__file__).parent / "vectors" / "slcs1.json"
DOC = json.loads(VECTORS_PATH.read_text(encoding="utf-8"))


# --------------------------------------------------------------------------------------
# the tagged input dialect
# --------------------------------------------------------------------------------------


def _tag_repeat(spec: Any) -> str:
    return str(spec["value"]) * int(spec["count"])


def _tag_nest(spec: Any) -> Any:
    depth = int(spec["depth"])
    if spec["kind"] == "list":
        node: Any = []
        for _ in range(depth - 1):
            node = [node]
        return node
    node = {}
    for _ in range(depth - 1):
        node = {spec["key"]: node}
    return node


def _tag_object(spec: Any) -> Any:
    return {decode(key): decode(value) for key, value in spec}


def _tag_nonfinite(spec: Any) -> float:
    return float({"nan": "nan", "infinity": "inf", "-infinity": "-inf"}[spec])


TAGS = {
    "$str": lambda v: v,
    "$int": lambda v: int(v),
    "$float": lambda v: float(v),
    "$decimal": lambda v: Decimal(v),
    "$bytes": lambda v: v.encode("utf-8"),
    "$datetime": lambda v: datetime.fromisoformat(v),
    "$codepoint": lambda v: chr(int(v)),
    "$tuple": lambda v: tuple(decode(x) for x in v),
    "$set": lambda v: {decode(x) for x in v},
    "$date": lambda v: datetime.fromisoformat(v).date(),
    "$object": _tag_object,
    "$repeat": _tag_repeat,
    "$nest": _tag_nest,
    "$nonfinite": _tag_nonfinite,
}


def decode(node: Any) -> Any:
    """Turn a tagged JSON node into the Python value the vector describes."""
    if isinstance(node, dict):
        tagged = [key for key in node if key.startswith("$")]
        if tagged:
            assert len(node) == 1, f"a tagged node carries exactly one key: {sorted(node)}"
            return TAGS[tagged[0]](node[tagged[0]])
        return {key: decode(value) for key, value in node.items()}
    if isinstance(node, list):
        return [decode(item) for item in node]
    return node


def ids(entries):
    return [entry["name"] for entry in entries]


# --------------------------------------------------------------------------------------
# accepted vectors
# --------------------------------------------------------------------------------------


@pytest.mark.parametrize("vector", DOC["vectors"], ids=ids(DOC["vectors"]))
def test_vector_encodes_to_the_frozen_bytes(vector):
    produced = canonicalize(decode(vector["input"]))
    assert produced == bytes.fromhex(vector["canonical_hex"])


@pytest.mark.parametrize("vector", DOC["vectors"], ids=ids(DOC["vectors"]))
def test_vector_hex_is_the_utf8_encoding_of_its_text_form(vector):
    """The two published forms of every expectation must agree with each other."""
    assert bytes.fromhex(vector["canonical_hex"]).decode("utf-8") == vector["canonical"]


@pytest.mark.parametrize("vector", DOC["vectors"], ids=ids(DOC["vectors"]))
def test_vector_sha256_matches_its_canonical_bytes(vector):
    digest = hashlib.sha256(bytes.fromhex(vector["canonical_hex"])).hexdigest()
    assert digest == vector["sha256"]


# --------------------------------------------------------------------------------------
# rejected vectors
# --------------------------------------------------------------------------------------


@pytest.mark.parametrize("vector", DOC["rejects"], ids=ids(DOC["rejects"]))
def test_reject_vector_is_refused_with_the_documented_message(vector):
    with pytest.raises(CanonicalizationError) as excinfo:
        canonicalize(
            decode(vector["input"]),
            allow_datetime=vector.get("allow_datetime", True),
        )
    assert vector["error_contains"] in str(excinfo.value)


# --------------------------------------------------------------------------------------
# entry preimage and genesis vectors
# --------------------------------------------------------------------------------------


@pytest.mark.parametrize("vector", DOC["entries"], ids=ids(DOC["entries"]))
def test_entry_preimage_matches_the_frozen_bytes(vector):
    entry = Entry(**{key: decode(value) for key, value in vector["entry"].items()})
    assert entry_preimage(entry) == bytes.fromhex(vector["preimage_hex"])


@pytest.mark.parametrize("vector", DOC["entries"], ids=ids(DOC["entries"]))
def test_entry_hash_matches_the_frozen_digest(vector):
    entry = Entry(**{key: decode(value) for key, value in vector["entry"].items()})
    for algorithm, expected in vector["hashes"].items():
        assert HashChain(algorithm).calculate_hash(entry) == expected


@pytest.mark.parametrize("vector", DOC["genesis"], ids=ids(DOC["genesis"]))
def test_genesis_vector_matches_the_frozen_digest(vector):
    produced = genesis_hash(
        vector["ledger_id"],
        decode(vector["created_at"]),
        vector["format_version"],
    )
    assert produced == vector["sha256"]


# --------------------------------------------------------------------------------------
# the vector file itself
# --------------------------------------------------------------------------------------


REQUIRED_CATEGORIES = {"unicode", "key-order", "nesting", "numeric-edge", "datetime"}


def test_every_required_category_is_covered():
    covered = {vector["name"].split("/")[0] for vector in DOC["vectors"]}
    assert covered >= REQUIRED_CATEGORIES


def test_vector_names_are_unique():
    names = [v["name"] for v in DOC["vectors"] + DOC["rejects"] + DOC["entries"]]
    assert len(names) == len(set(names))


def test_the_file_declares_the_spec_it_freezes():
    assert DOC["spec"] == "SLCS/1"


def test_the_file_documents_its_own_input_dialect():
    """A second-language implementer must be able to read the file without this repo."""
    assert set(DOC["dialect"]) == set(TAGS)
